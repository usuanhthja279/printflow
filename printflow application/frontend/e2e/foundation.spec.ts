import {test,expect} from '@playwright/test';

test('customer enquiry, secure staff follow-up, manual intake and tracking',async({page},testInfo)=>{
 const name=`Browser Synthetic ${Date.now()}`;
 await page.goto('/');
 await expect(page.getByRole('link',{name:'J.D.Printex Home'})).toBeVisible();
 for(const [label,code] of [['Shaadi & wedding cards','WEDDING_CARDS'],['Hotel print materials','HOTEL_PRINT'],['Pamphlets & leaflets','BROCHURES'],['Offset gloss printing','OFFSET_GLOSS']]){
  await page.getByRole('link').filter({has:page.getByRole('heading',{name:label,exact:true})}).click();
  await page.waitForURL(`**/request-quote?product=${code}`);
  await expect(page.getByRole('combobox',{name:'Print product',exact:true})).toHaveValue(code);
  await page.goto('/');
 }
 await page.goto('/request-quote?product=WEDDING_CARDS');
 await page.getByLabel('Your name').fill(name);
 await page.getByLabel('Email address').fill('browser@example.test');
 await page.getByLabel('Phone number').fill('9000000000');
 await page.getByRole('checkbox').check();
 await page.getByRole('button',{name:'Submit enquiry'}).click();
 await expect(page.getByRole('heading',{name:'Enquiry saved successfully'})).toBeVisible();
 const id=await page.locator('.credential code').nth(0).innerText();
 const token=await page.locator('.credential code').nth(1).innerText();
 await page.goto('/business');
 await page.getByLabel('Staff username').fill(process.env.APP_STAFF_BOOTSTRAP_USERNAME||'');
 await page.getByLabel('Password',{exact:true}).fill(process.env.APP_STAFF_BOOTSTRAP_PASSWORD||'');
 await page.getByRole('button',{name:'Sign in',exact:true}).click();
 await page.getByLabel('Search enquiries').fill(name);
 const row=page.getByRole('row').filter({hasText:name});
 await expect(row).toBeVisible();
 await row.getByRole('button',{name:'Open enquiry'}).click();
 await page.getByRole('button',{name:'Assign to me',exact:true}).click();
 await expect(page.getByRole('button',{name:'Start reviewing',exact:true})).toBeEnabled();
 const updated=page.waitForResponse(r=>r.request().method()==='PATCH'&&r.url().includes('/status'));
 await page.getByRole('button',{name:'Start reviewing',exact:true}).click();
 expect((await updated).status()).toBe(200);
 await page.getByRole('combobox',{name:'Priority',exact:true}).selectOption('HIGH');
 await page.getByLabel('Next action',{exact:true}).fill('Confirm paper and delivery requirements');
 const past=new Date(Date.now()-86400000);
 const local=new Date(past.getTime()-past.getTimezoneOffset()*60000).toISOString().slice(0,16);
 await page.getByLabel('Follow-up time (your local time)',{exact:true}).fill(local);
 const saved=page.waitForResponse(r=>r.request().method()==='PATCH'&&r.url().includes('/follow-up'));
 await page.getByRole('button',{name:'Save follow-up',exact:true}).click();
 expect((await saved).status()).toBe(200);
 await page.reload();
 await page.getByLabel('Search enquiries').fill(name);
 await page.getByLabel('Queue filter').selectOption('OVERDUE');
 await expect(page.getByRole('row').filter({hasText:name})).toContainText('Confirm paper and delivery requirements');
 await expect(page.getByRole('row').filter({hasText:name})).toContainText('HIGH priority');
 await page.getByRole('row').filter({hasText:name}).getByRole('button',{name:'Open enquiry'}).click();
 await expect(page.getByText('FOLLOW UP UPDATED',{exact:true})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await page.screenshot({path:testInfo.outputPath('staff-follow-up.png'),fullPage:true});
 await page.goto('/track');
 await page.getByLabel('Enquiry ID').fill(id);
 await page.getByLabel('Secure tracking token').fill(token);
 await page.getByRole('button',{name:'Check status'}).click();
 await expect(page.locator('.status-chip')).toHaveText('REVIEWING');
 await expect(page.locator('.timeline-event')).toHaveCount(2);
 await expect(page.getByText('Confirm paper and delivery requirements',{exact:true})).toHaveCount(0);
 await page.goto('/business');
 await page.getByRole('button',{name:'Add enquiry',exact:true}).click();
 await page.getByLabel('Customer name',{exact:true}).fill(`Staff ${name}`);
 await page.getByLabel('Customer email',{exact:true}).fill('manual@example.test');
 await page.getByLabel('Customer phone',{exact:true}).fill('9000000000');
 await page.getByLabel('Enquiry source').selectOption('PHONE');
 await page.getByLabel('Requested product').selectOption('HOTEL_PRINT');
 await page.getByRole('button',{name:'Save enquiry',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Enquiry created',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Dismiss credentials'}).click();
 await expect(page.getByRole('row').filter({hasText:`Staff ${name}`})).toContainText('PHONE');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await page.getByLabel('Open account menu').click();await page.getByRole('button',{name:'Sign out',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Staff sign in'})).toBeVisible();
 await page.reload();
 await expect(page.getByRole('heading',{name:'Staff sign in'})).toBeVisible();
});
